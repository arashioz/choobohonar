/** گوگل عنوان فارسی را حدود ۴۰ تا ۵۲ نویسه نشان می‌دهد؛ بیشتر از آن برش می‌خورد. */
export function serpTitleFit(title: string) {
  const n = [...title].length;
  if (n <= 42) return { n, label: "مناسب اسنیپت", tone: "ok" as const };
  if (n <= 52) return { n, label: "لبهٔ برش", tone: "warn" as const };
  return { n, label: "برش می‌خورد", tone: "bad" as const };
}

